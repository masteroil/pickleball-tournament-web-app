export function makeMixed(){
 const category={id:mixedId,name:'Mixed Doubles — DUPR Match-ups',format:'doubles',competition:'rotation',method:'sideout',target:11,winBy:1,teams:[...mixedPlayers],groups:[]};
 const matches=mixedRounds.flatMap((games,round)=>games.map((g,index)=>({id:`${mixedId}-r${round+1}-c${index+1}`,category:mixedId,round,index,a:g.a.join(' & '),b:g.b.join(' & '),playersA:[...g.a],playersB:[...g.b],averages:g.averages,scheduledCourt:index+1,sa:0,sb:0,serving:0,server:2,opening:true,court:null,status:round===0?'ready':'waiting',history:[]})));
 return {category,matches};
}
export function addMixed(s:any):boolean{
 if(s.categories.some((c:any)=>c.id===mixedId))return false;
 const {category,matches}=makeMixed();s.categories.push(category);s.matches.push(...matches);return true;
}
export function finishRotation(matches:any[],m:any){
 if(matches.some(x=>x.category===m.category&&x.round===m.round&&x.status!=='completed'))return;
 for(const next of matches.filter(x=>x.category===m.category&&x.round===m.round+1&&x.status==='waiting'))next.status='ready';
}
export function standings(category:any,matches:any[]){
 const rows=new Map<string,{name:string;played:number;wins:number;losses:number;for:number;against:number;difference:number;rank:number}>();
 for(const name of category.teams as string[])rows.set(name,{name,played:0,wins:0,losses:0,for:0,against:0,difference:0,rank:1});
 for(const m of matches.filter(m=>m.category===category.id&&m.status==='completed')){
  for(const [names,scored,conceded] of [[m.playersA,m.sa,m.sb],[m.playersB,m.sb,m.sa]] as [string[],number,number][]){
   for(const name of names){const r=rows.get(name);if(!r)continue;r.played++;r.wins+=Number(scored>conceded);r.losses+=Number(scored<conceded);r.for+=scored;r.against+=conceded;r.difference=r.for-r.against;}
  }
 }
 const sorted=[...rows.values()].sort((a,b)=>b.wins-a.wins||b.difference-a.difference||b.for-a.for||a.name.localeCompare(b.name));
 sorted.forEach((r,i)=>{const p=sorted[i-1];r.rank=p&&p.wins===r.wins&&p.difference===r.difference&&p.for===r.for?p.rank:i+1});return sorted;
}
